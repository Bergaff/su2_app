def show_legal_document(parent, kind="tos"):
    """Открывает окно с выбранным документом. Возвращает сам диалог."""
    if kind not in DOCUMENTS:
        raise ValueError(f"Неизвестный документ: {kind!r}. "
                         f"Доступны: {', '.join(DOCUMENTS)}")
    title, body = DOCUMENTS[kind]

    from PyQt5.QtWidgets import (QDialog, QHBoxLayout, QLabel, QPushButton,
                                 QTextBrowser, QVBoxLayout)

    dlg = QDialog(parent)
    dlg.setWindowTitle(title)
    dlg.resize(680, 620)
    dlg.setStyleSheet(_DIALOG_STYLE)

    lay = QVBoxLayout(dlg)
    lay.setContentsMargins(12, 12, 12, 12)
    lay.setSpacing(8)

    header = QLabel(title)
    header.setStyleSheet("font-size: 13px; font-weight: bold; color: #22384A;")
    lay.addWidget(header)

    viewer = QTextBrowser()
    viewer.setPlainText(body)
    viewer.setOpenExternalLinks(False)
    lay.addWidget(viewer, 1)

    buttons = QHBoxLayout()
    buttons.addStretch(1)
    btn_close = QPushButton("Закрыть")
    btn_close.clicked.connect(dlg.accept)
    buttons.addWidget(btn_close)
    lay.addLayout(buttons)

    dlg.exec_()
    return dlg


def install_menu(main_window):
    """Добавляет меню «Справка» с разделом правовой информации."""
    try:
        menu_bar = main_window.menuBar()
    except AttributeError:
        return None

    menu = menu_bar.addMenu("Справка")

    def _tos():
        show_legal_document(main_window, "tos")

    def _privacy():
        show_legal_document(main_window, "privacy")

    act_tos = menu.addAction("Условия использования")
    act_tos.triggered.connect(_tos)
    act_privacy = menu.addAction("Политика конфиденциальности")
    act_privacy.triggered.connect(_privacy)
    return menu
