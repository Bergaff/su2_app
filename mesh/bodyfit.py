# ЧТО ЗДЕСЬ ДОЛЖНО БЫТЬ И ПОЧЕМУ ЭТОГО ПОКА НЕТ
#
# Подготовка поверхности работает и покрыта тестами. Объёмная сетка по ней
# не строится, и это не недосмотр, а измеренный тупик именно этого
# способа уплотнения.
#
# Бисекция длинного ребра делит каждое ребро пополам и не трогает
# короткие. Исходная триангуляция сильно анизотропна: у оперения
# короткое ребро 0.0011 м при длинном 1.200 м. За шесть проходов
# короткое становится 1.7e-05 м, и поверхность покрывается иголками —
# средняя площадь грани 4e-05 м2 при целевом ребре 0.06 м. Топологически
# такая сетка безупречна (0 рёбер с одним соседом, 0 дублей, watertight,
# объём сохранён), но геометрически иголки на криволинейной поверхности
# заворачиваются друг на друга.
#
# Проверено на полном самолёте (5 тел, объединение 5296 граней,
# уплотнение до 304874):
#
#   gmsh, mesh.embed + Algorithm3D=1
#       не закончил generate(3) за 900 с даже для ОДНОГО оперения
#       с 77522 встроенными треугольниками;
#   TetGen, порог слияния _span*1e-7
#       "The input surface mesh contain self-intersections.";
#   TetGen, порог _span*1e-5
#       "Internal TetGen error within split_segment.";
#   TetGen, порог _span*1e-4
#       SIGSEGV, код возврата 139.
#
# То есть ни один объёмный сеточник такую поверхность не принимает.
# Лечится это не подбором порога, а заменой способа: поверхность нужно
# ПЕРЕСТРАИВАТЬ (2D-Делоне на поверхности с полем размеров), а не делить
# существующую триангуляцию. Это отдельный алгоритм.
#
# Сам TetGen при этом быстрый и для хорошей поверхности годится: на
# уплотнённом одиночном оперении он дал 715854 тетраэдра за 5.7 с —
# против gmsh, который на том же входе не закончил за 900 с.
#
# ГОТОВЫЙ РЕ-МЕШЕР ПРОВЕРЕН И ТОЖЕ НЕ СПАСАЕТ (pyacvd 0.4.0 и 0.3.4,
# ядро одно и то же — числа совпадают до грани). Он действительно делает
# поверхность изотропной: на этом самолёте медианное ребро падает с
# 0.2814 до 0.02165, объём сохраняется (6.978148 -> 6.996387, +0.26%),
# площадь 42.74 -> 43.08. Но create_mesh() возвращает НЕзамкнутую сетку:
# 355-446 рёбер с одним соседом и 571-749 рёбер с тремя и больше.
# Склеивание вершин не помогает (при tol 1e-6..1e-3 цифры не меняются,
# при 1e-3 становится хуже), то есть это настоящие дыры, а не дубли.
# TetGen на ней отвечает "Internal TetGen error within recoversubfaces".
#
# Отдельно: clean_surface с порогом 1e-4 от габарита на объединении сам
# вносит 4 граничных и 24 не-многообразных ребра. Перед ре-мешером его
# применять нельзя.


def volume_mesher_status():
    """Честный отчёт о том, что объёмная сетка пока не строится.

    Вызывается вместо попыток построить сетку, чтобы пользователь видел
    причину, а не аварийное завершение процесса.
    """
    return {
        "ready": False,
        "surface_ready": True,
        "reason": ("поверхность после уплотнения покрыта иголками: бисекция "
                   "делит длинное ребро и не трогает короткое, а исходная "
                   "триангуляция анизотропна. Топологически сетка чистая, "
                   "но геометрически иголки заворачиваются друг на друга, и "
                   "объёмные сеточники её отвергают."),
        "tried": {
            "gmsh embed + Algorithm3D=1": "не закончил за 900 с на одном оперении",
            "TetGen, порог 1e-7": "self-intersections",
            "TetGen, порог 1e-5": "Internal error within split_segment",
            "TetGen, порог 1e-4": "SIGSEGV (139)",
            "pyacvd 0.4.0 / 0.3.4": ("изотропность даёт (0.2814 -> 0.02165), "
                                     "но create_mesh() возвращает незамкнутую "
                                     "сетку: 355-446 граничных рёбер, "
                                     "571-749 не-многообразных; TetGen — "
                                     "recoversubfaces"),
        },
        "fix": ("перестраивать поверхность 2D-Делоном с полем размеров "
                "вместо деления существующей триангуляции; готовые ре-мешеры "
                "проверены и замкнутости не дают"),
    }
