def clean_surface(vertices, faces, tol):
    """Сливает близкие вершины и выбрасывает вырожденные грани.

    Нужен потому, что gmsh отвергает поверхность с иголками: на
    уплотнённом самолёте минимальное ребро доходило до 7.9e-09 м, и
    generate(3) падал с «Invalid boundary mesh (overlapping facets)».

    Источник иголок — исходная триангуляция: сечение NACA строится с
    кластеризацией к передней и задней кромке, там рёбра по 0.0011 м.
    Бисекция делит их дальше, и после четырёх проходов получаются рёбра
    на порядки меньше машинной точности координат.

    ``tol`` — порог слияния; берётся от целевого шага, а не абсолютный.
    """
    v = np.asarray(vertices, dtype=float)
    f = np.asarray(faces, dtype=np.int64)
    if len(v) == 0 or len(f) == 0 or tol <= 0:
        return v, f

    # квантование координат: вершины ближе tol становятся одной
    q = np.round(v / tol).astype(np.int64)
    _, inv = np.unique(q, axis=0, return_inverse=True)
    nf = inv[f]

    # грани, схлопнувшиеся в отрезок или точку
    ok = (nf[:, 0] != nf[:, 1]) & (nf[:, 1] != nf[:, 2]) & (nf[:, 2] != nf[:, 0])
    nf = nf[ok]

    # Слияние вершин складывает соседние грани: две разные грани после
    # перенумерации становятся одним и тем же набором индексов, а иногда
    # и перевёрнутой копией друг друга. Без этого шага clean_surface сам
    # портил поверхность — на объединённом самолёте появлялось 17 дублей
    # и 34 не-многообразных ребра, и TetGen отвечал «input surface mesh
    # contain self-intersections».
    if len(nf):
        key = np.sort(nf, axis=1)
        _, uniq_idx = np.unique(key, axis=0, return_index=True)
        nf = nf[np.sort(uniq_idx)]
    if len(nf) == 0:
        return v, f

    # новые координаты — среднее по слитой группе
    sums = np.zeros((inv.max() + 1, 3))
    cnt = np.zeros(inv.max() + 1)
    np.add.at(sums, inv, v)
    np.add.at(cnt, inv, 1.0)
    nv = sums / cnt[:, None]

    # убираем неиспользуемые вершины
    used = np.unique(nf)
    remap = -np.ones(len(nv), dtype=np.int64)
    remap[used] = np.arange(len(used))
    return nv[used], remap[nf]


def prepare_surface(bodies, budget_faces=600_000, progress_cb=None):
    """Уплотняет поверхности и объединяет их в одну замкнутую.

    ``bodies`` — список ``(vertices, faces)``, ``faces`` — треугольники
    либо квады с префиксом числа вершин (как даёт pyvista).

    Возвращает ``(vertices, faces, info)`` объединённой поверхности.
    ``info["not_volumes"]`` перечисляет индексы тел, которые не удалось
    использовать, — их надо показать пользователю, а не проглотить.
    """
    if not HAS_TRIMESH:
        raise RuntimeError("нужен trimesh для объединения тел")

    def _tri(f):
        """Треугольники из любого представления граней.

        pyvista отдаёт ``.faces`` ПЛОСКИМ массивом [3,i,j,k, 3,i,j,k,...],
        поэтому первым делом проверяется одномерный случай. Первая
        версия требовала двумерный массив и молча возвращала пусто — все
        пять тел отбрасывались как «пустые», объединение давало 0 граней.
        """
        f = np.asarray(f)
        if f.size == 0:
            return np.zeros((0, 3), dtype=np.int64)
        if f.ndim == 1:
            f = f.reshape(-1, int(f[0]) + 1)
        if f.ndim != 2 or f.shape[1] == 0:
            return np.zeros((0, 3), dtype=np.int64)
        if f.shape[1] == 3:
            return f.astype(np.int64)
        # [n, i, j, k, ...] — префикс есть число вершин грани
        n = int(f[0, 0])
        return f[:, 1:n + 1].astype(np.int64)

    clean = []
    skipped = []
    for i, (v, f) in enumerate(bodies):
        v = np.asarray(v, dtype=float)
        t = _tri(f)
        if len(v) == 0 or len(t) == 0:
            skipped.append((i, "пустое тело"))
            continue
        # Иголки убираются ДО объединения и уплотнения: бисекция делит
        # каждое ребро пополам, и исходные 0.0011 м за четыре прохода
        # становятся 7e-11 м.
        ext = v.max(axis=0) - v.min(axis=0)
        _tol = float(ext.max()) * 1e-6 if len(v) else 0.0
        if _tol > 0:
            v, t = clean_surface(v, t, _tol)
            if len(t) == 0:
                skipped.append((i, "схлопнулось при очистке"))
                continue
        clean.append((v, t))

    # Заполняется целиком сразу: вызывающий код печатает отчёт по всем
    # полям, и ранний выход не должен оставлять дыр в словаре.
    info = {"not_volumes": skipped, "n_input": len(bodies),
            "faces_after_union": 0, "watertight": False,
            "refined_faces": 0, "target_min": 0.0, "target_max": 0.0,
            "area": 0.0, "capped": False, "reached": True}
    if not clean:
        return np.zeros((0, 3)), np.zeros((0, 3), np.int64), info

    # 1. объединение исходных тел. Делается ДО уплотнения: объединение
    #    само упрощает компланарные области (58630 граней на входе ->
    #    6452 на выходе), то есть плотная триангуляция до объединения
    #    просто выбрасывается.
    tms = []
    for v, t in clean:
        tms.append(trimesh.Trimesh(v, t, process=False))

    bad = [i for i, m in enumerate(tms) if not m.is_volume]
    if bad:
        for i in bad:
            info["not_volumes"].append((i, "не является объёмом"))
        good = [m for i, m in enumerate(tms) if i not in set(bad)]
        if not good:
            raise RuntimeError(
                "ни одно тело не является замкнутым объёмом — объединить "
                "нельзя; тела: %s" % [i for i, _ in info["not_volumes"]])
        tms = good

    u = trimesh.boolean.union(tms, engine="manifold")
    uv = np.asarray(u.vertices, dtype=float)
    uf = np.asarray(u.faces, dtype=np.int64)

    # Объединение само создаёт вырожденные рёбра: на этом самолёте
    # минимальное ребро после union было 6.311e-08 м. Их надо убрать
    # сейчас, пока сетка грубая (5404 грани) и слияние вершин
    # однозначное. После уплотнения тот же порог уже складывает
    # соседние грани и портит поверхность.
    _span = float((uv.max(axis=0) - uv.min(axis=0)).max()) if len(uv) else 0.0
    if _span > 0:
        uv, uf = clean_surface(uv, uf, _span * 1e-4)

    info["faces_after_union"] = int(len(uf))
    info["watertight"] = bool(u.is_watertight)
    info["area"] = float(u.area)
    if progress_cb:
        progress_cb("поверхности объединены: %d граней" % len(uf))

    # 2. поле целевых шагов и уплотнение уже объединённой поверхности.
    body_pts = [v for v, _ in clean]
    body_tris = [t for _, t in clean]
    tgt = target_field_from_bodies(uv, uf, body_pts, body_faces=body_tris)
    if len(tgt):
        info["target_min"] = float(tgt.min())
        info["target_max"] = float(tgt.max())

    rv, rf, ri = refine_to_edge_length(uv, uf, tgt, max_faces=budget_faces)
    # После уплотнения поверхность уже не чистится: слияние вершин на
    # мелкой сетке складывает грани. Измерено — на этом самолёте чистка
    # с порогом tgt.min()*1e-2 давала 17 дублей и 34 не-многообразных
    # ребра, и TetGen отвечал «self-intersections».
    info["refined_faces"] = int(len(rf))
    info["capped"] = bool(ri.get("capped"))
    info["reached"] = bool(ri.get("reached"))
    return rv, rf, info


