# -*- coding: utf-8 -*-
"""mesh/bodyfit.py — подготовка поверхности для телооблегающей сетки.

Почему это отдельный путь
-------------------------
Основной генератор (``mesh/gmsh_generator.py``) строит структурированный
фон и вырезает из него ячейки, чей центр попал внутрь тела. Поверхность
тела при этом получается ступенчатой, из граней фона, а шаг считается от
РАЗМАХА модели: при качестве «Средняя» и размахе 9.02 м это 0.135 м.

Разрешать же нужно не размах, а толщину. У оперения (корневая хорда
0.56 м, профиль 12%) толщина 0.067 м — половина шага фона. В зависимости
от того, как легла сетка, внутрь попадает 0 или 1 слой ячеек.

Уменьшить шаг нельзя: он ограничен строкой ``h_near = max(h_near,
body_size*0.015)`` не произвольно, а по памяти. Измерено: шаг 0.028 м на
этой геометрии требует ~41.2 млн точек фона и ~250 млн тетраэдров до
вырезания, процесс погибает. Фон структурированный, сгущение не
локальное, рост кубический.

Здесь сгущение локальное: мелкий шаг живёт только у тонких поверхностей,
а крупный остаётся на фюзеляже, которому он не нужен.

Что делает этот модуль
----------------------
``prepare_surface`` принимает тела в любом виде, в котором они приходят в
приложение — собственные генераторы, импортированный STL, STEP через
конвертер, — и отдаёт одну замкнутую триангулированную поверхность с
шагом, согласованным с местной толщиной:

1. Тела, не являющиеся замкнутым объёмом, отбрасываются с пометкой, а не
   молча и не падением.
2. Остальные объединяются в одну замкнутую поверхность
   (``trimesh.boolean.union``, движок manifold). Без объединения
   объёмный сеточник падает на пересекающихся компонентах: корень крыла
   заделан в фюзеляж, оперение — в фюзеляж.
3. Грубое объединение чистится от нулевых рёбер, которые оставляет
   логическое объединение (на этом самолёте — до 6.3e-08 м).
4. Поле целевых шагов задаёт мелкий шаг у тонких тел и крупный вдали,
   и поверхность уплотняется в рамках бюджета граней.

Бюджет соблюдается честно: на этом самолёте 200000 дают 304874 грани,
600000 — 519252, площадь поверхности в обоих случаях ровно 42.74 м2.

Чего этот модуль НЕ делает
--------------------------
Объёмную сетку он не строит. Это не недосмотр, а измеренный тупик именно
этого способа уплотнения — подробности и все прогнанные варианты в
``volume_mesher_status()``.

Полезно знать о сторонних сеточниках
------------------------------------
Ни gmsh, ни TetGen не переразбивают поданную им поверхность, они строят
объём строго по заданной триангуляции. gmsh при
``Mesh.CharacteristicLengthMax`` 0.20 и 0.05 даёт одинаковые 12
треугольников на импортированном боксе, ``setCompound(2, ...)`` тоже
ничего не меняет. Поэтому шаг придётся задавать самим — это шаг 4.

``Mesh.Algorithm3D=4`` (Frontal) с пересекающимися телами не падает, но
и ``mesh.embed`` игнорирует: 112 точек из 115955 легли на поверхность.
Поэтому нужно именно объединение плюс ``Algorithm3D=1``.
"""

